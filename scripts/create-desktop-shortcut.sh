#!/bin/bash
# Create "AI Test Coverage.app" on the user Desktop with custom icon (ai-test-coverage.icns).
# Mirrors create-desktop-shortcut.ps1 for macOS.
# Run: bash scripts/create-desktop-shortcut.sh

set -e

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DESKTOP="$HOME/Desktop"
APP_NAME="AI Test Coverage"
APP_PATH="$DESKTOP/${APP_NAME}.app"
PNG_PATH="$PROJECT_ROOT/assets/ai-test-coverage.png"
ICNS_PATH="$PROJECT_ROOT/assets/ai-test-coverage.icns"

# Bump whenever the generated launcher changes. ensure-desktop-shortcut.sh greps
# an installed bundle for this stamp and rebuilds when it does not match, so a
# `git pull` that changes the launcher is picked up on the next `npm run web`.
LAUNCHER_VERSION="3"

if [ ! -f "$PNG_PATH" ]; then
  echo "Missing icon: $PNG_PATH" >&2
  exit 1
fi

# Build a multi-resolution .icns from the PNG if missing.
# Uses macOS-bundled sips + iconutil; both ship with every macOS install.
if [ ! -f "$ICNS_PATH" ]; then
  if ! command -v sips >/dev/null 2>&1 || ! command -v iconutil >/dev/null 2>&1; then
    echo "sips/iconutil not found — cannot build .icns icon." >&2
    exit 1
  fi
  TMP_ROOT="$(mktemp -d)"
  ICONSET="$TMP_ROOT/AppIcon.iconset"
  mkdir -p "$ICONSET"
  for size in 16 32 128 256 512; do
    double=$((size * 2))
    sips -z "$size" "$size" "$PNG_PATH" --out "$ICONSET/icon_${size}x${size}.png" >/dev/null
    sips -z "$double" "$double" "$PNG_PATH" --out "$ICONSET/icon_${size}x${size}@2x.png" >/dev/null
  done
  iconutil -c icns "$ICONSET" -o "$ICNS_PATH"
  rm -rf "$TMP_ROOT"
fi

# (Re)create the .app bundle. Removing first keeps the operation idempotent.
rm -rf "$APP_PATH"
mkdir -p "$APP_PATH/Contents/MacOS"
mkdir -p "$APP_PATH/Contents/Resources"

cp "$ICNS_PATH" "$APP_PATH/Contents/Resources/AppIcon.icns"

# The server script Terminal.app actually runs, so `npm run web` gets a real
# window with live logs that can be stopped with Ctrl+C (the Windows shortcut
# has always opened a console this way; macOS used to start it detached).
# `.command` is the extension Terminal opens on double-click / `open -a Terminal`.
SERVER_COMMAND="$APP_PATH/Contents/Resources/start-server.command"
{
  printf '#!/bin/zsh -l\n'
  printf '# Generated by create-desktop-shortcut.sh — starts the AI Test Coverage web UI.\n'
  printf 'cd %q || exit 1\n' "$PROJECT_ROOT"
  printf 'echo "AI Test Coverage — npm run web (Ctrl+C to stop)"\n'
  printf 'exec npm run web\n'
} > "$SERVER_COMMAND"
chmod +x "$SERVER_COMMAND"

cat > "$APP_PATH/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key>
  <string>${APP_NAME}</string>
  <key>CFBundleDisplayName</key>
  <string>${APP_NAME}</string>
  <key>CFBundleIdentifier</key>
  <string>com.aitestcoverage.ai-test-coverage</string>
  <key>CFBundleVersion</key>
  <string>1.0</string>
  <key>CFBundleShortVersionString</key>
  <string>1.0</string>
  <key>CFBundleExecutable</key>
  <string>launcher</string>
  <key>CFBundleIconFile</key>
  <string>AppIcon</string>
  <key>CFBundlePackageType</key>
  <string>APPL</string>
</dict>
</plist>
PLIST

LAUNCHER_BIN="$APP_PATH/Contents/MacOS/launcher"
#
# Self-contained launcher: embeds PROJECT_ROOT at build time.
#
# macOS 26+ silently sandboxes unsigned .app bundles on the Desktop (no TCC
# prompt, just "Operation not permitted"). Reading the external launch-*.sh
# from inside the .app fails. So the launcher CANNOT depend on any file
# outside the bundle. To then spawn `npm run web` outside the sandbox we hand
# the work to an Apple-signed binary: `/usr/bin/open` (preferred, gives a
# visible Terminal window) or `/usr/bin/osascript` (fallbacks).
#
# We build the launcher in two parts: a header that embeds PROJECT_ROOT via
# `printf %q` (handles spaces / special chars), then a quoted heredoc body
# that keeps every $var literal.
{
  printf '#!/bin/bash\n'
  printf '# Self-contained launcher for AI Test Coverage.app — see create-desktop-shortcut.sh.\n'
  printf '# launcher-version: %s\n' "$LAUNCHER_VERSION"
  printf 'PROJECT_ROOT=%q\n' "$PROJECT_ROOT"
  cat <<'LAUNCHER_BODY'
PORT="${WEB_UI_PORT:-3847}"
WEB_URL="http://127.0.0.1:${PORT}/"
HEALTH_URL="${WEB_URL}__da/health"
LOG_FILE="/tmp/ai-test-coverage.log"

log() {
  printf '[%s] %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*" >> "$LOG_FILE" 2>&1
}

log "launcher start, URL=$WEB_URL, PROJECT_ROOT=$PROJECT_ROOT"

is_up() {
  /usr/bin/curl -sf -o /dev/null --max-time 2 "$HEALTH_URL"
}

# Preferred: hand the bundled .command to Terminal.app, which opens a real
# window running `npm run web` in the foreground — live logs, Ctrl+C to stop.
# `open` is Apple-signed, so the server escapes the .app sandbox, and passing a
# path is not the sandboxed launcher reading the file (Terminal reads it).
start_server_in_terminal() {
  local cmd_file="$(dirname "$0")/../Resources/start-server.command"
  if [ ! -f "$cmd_file" ]; then
    log "no start-server.command in bundle"
    return 1
  fi
  log "opening Terminal with $cmd_file"
  /usr/bin/open -a Terminal "$cmd_file" >> "$LOG_FILE" 2>&1 || return 1
  log "Terminal launched"
}

# Fallback: drive Terminal over Apple Events. Still a visible window, but needs
# the one-time "wants to control Terminal" Automation prompt, which an unsigned
# bundle does not always get.
start_server_via_applescript() {
  local escaped_root="${PROJECT_ROOT//\'/\'\\\'\'}"
  local shell_cmd="cd '${escaped_root}' && npm run web"
  # Escape for an AppleScript string literal: backslashes first, then quotes.
  local as_cmd="${shell_cmd//\\/\\\\}"
  as_cmd="${as_cmd//\"/\\\"}"
  log "falling back to AppleScript do script"
  /usr/bin/osascript \
    -e 'tell application "Terminal"' \
    -e "do script \"${as_cmd}\"" \
    -e 'activate' \
    -e 'end tell' \
    >> "$LOG_FILE" 2>&1
}

# Last resort: the old detached start. No window to Ctrl+C, but the UI works.
start_server_detached() {
  # Escape single quotes in PROJECT_ROOT for the inner sh string.
  local escaped_root="${PROJECT_ROOT//\'/\'\\\'\'}"
  local shell_cmd
  shell_cmd="cd '${escaped_root}' && exec /bin/zsh -lc 'npm run web'"
  log "spawning detached via osascript: $shell_cmd"
  # Detach stdio (</dev/null + redirect) so `do shell script` does not hang
  # waiting for the captured pipe to close.
  /usr/bin/osascript \
    -e "do shell script \"nohup /bin/sh -c \\\"$shell_cmd\\\" </dev/null >>${LOG_FILE} 2>&1 &\"" \
    >> "$LOG_FILE" 2>&1
  log "osascript returned"
}

if ! is_up; then
  log "server not up; starting"
  start_server_in_terminal || start_server_via_applescript || start_server_detached
  deadline=$(( $(date +%s) + 45 ))
  while [ "$(date +%s)" -lt "$deadline" ]; do
    sleep 0.4
    if is_up; then
      log "server is up"
      break
    fi
  done
  if ! is_up; then
    log "server failed to come up within 45s"
  fi
else
  log "server already up"
fi

log "opening Chrome"
/usr/bin/open -b com.google.Chrome "$WEB_URL" >> "$LOG_FILE" 2>&1 && { log "Chrome opened via bundle id"; exit 0; }
/usr/bin/open -a "Google Chrome" "$WEB_URL" >> "$LOG_FILE" 2>&1 && { log "Chrome opened via name"; exit 0; }
log "Chrome not found; falling back to default browser"
/usr/bin/open "$WEB_URL" >> "$LOG_FILE" 2>&1
LAUNCHER_BODY
} > "$LAUNCHER_BIN"

chmod +x "$LAUNCHER_BIN"

# Touch the bundle so Finder refreshes the icon cache.
touch "$APP_PATH"

echo "Created: $APP_PATH"
echo "Icon:    $ICNS_PATH"
